#include <QApplication>

#include "CalculatorWindow.h"

int main(int argc, char* argv[])
{
    // QApplication — центральный объект любого приложения Qt Widgets.
    // Он должен быть создан раньше окон: через него Qt получает настройки
    // системы, управляет ресурсами интерфейса и обрабатывает события.
    QApplication application(argc, argv);

    // CalculatorWindow является верхним уровнем дерева виджетов. Все элементы,
    // которым окно назначено родителем, Qt удалит автоматически вместе с ним.
    CalculatorWindow window;

    // show не рисует окно самостоятельно, а сообщает системе, что его нужно
    // показать. Фактическая отрисовка происходит через цикл событий Qt.
    window.show();

    // exec запускает цикл событий. Он ждёт действия мыши и клавиатуры,
    // передаёт события нужным объектам и завершается после закрытия приложения.
    // Возвращаемое число становится кодом завершения всей программы.
    return application.exec();
}
